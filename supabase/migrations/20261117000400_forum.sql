create policy "Threads visible by category, removed ones hidden" on public.threads for select using (
  public.can_view_category(category_id)
  and (removed_at is null or author_id = (select auth.uid()) or public.is_moderator())
);
create policy "Members start threads as themselves" on public.threads for insert to authenticated
  with check (author_id = (select auth.uid()));
create policy "Authors edit their threads" on public.threads for update to authenticated
  using (author_id = (select auth.uid()) and removed_at is null)
  with check (author_id = (select auth.uid()));
create policy "Authors delete their threads" on public.threads for delete to authenticated
