-- Upper Echelon · the Forum: categories, threads, replies, votes, polls, drafts, revisions, search.

create table public.forum_categories (
  id smallint generated by default as identity primary key,
  slug text not null unique constraint category_slug check (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
  name text not null,
  description text not null,
  position smallint not null default 100,
  min_tier smallint not null default 0, -- 0: open to guests; n: members of tier n and above
  is_advice boolean not null default false, -- threads can have an accepted answer
  staff_only boolean not null default false, -- only staff and moderators may start threads
  created_at timestamptz not null default now()
);

create or replace function public.can_view_category(cat smallint)
returns boolean language sql stable security definer set search_path = '' as $$
  select public.is_moderator()
    or coalesce((select min_tier from public.forum_categories where id = cat), 99) <= public.member_tier();
$$;

-- array_to_string is only STABLE; tags are plain text, so this wrapper is safe to mark IMMUTABLE
-- for use in the generated search column.
create or replace function public.tags_text(t text[])
returns text language sql immutable parallel safe set search_path = '' as $$
  select array_to_string(t, ' ');
$$;

create table public.threads (
  id bigint generated always as identity primary key,
  category_id smallint not null references public.forum_categories (id),
  author_id uuid references public.profiles (id) on delete set null,
  title text not null constraint title_length check (char_length(title) between 6 and 140),
  body text not null constraint body_length check (char_length(body) between 1 and 20000),
  tags text[] not null default '{}' constraint tags_count check (coalesce(array_length(tags, 1), 0) <= 5),
  directory_test_id uuid references public.directory_tests (id) on delete set null,
  is_pinned boolean not null default false,
  is_locked boolean not null default false,
  is_official boolean not null default false,
  solved_post_id bigint,
  score integer not null default 0,
  reply_count integer not null default 0,
  last_activity_at timestamptz not null default now(),
  last_reply_by uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default now(),
  edited_at timestamptz,
  removed_at timestamptz,
  removed_by uuid references public.profiles (id) on delete set null,
  removed_reason text,
  search tsvector generated always as (
    setweight(to_tsvector('english', coalesce(title, '')), 'A')
    || setweight(to_tsvector('english', coalesce(public.tags_text(tags), '')), 'B')
    || setweight(to_tsvector('english', coalesce(body, '')), 'C')
  ) stored
);
create index threads_category_activity on public.threads (category_id, is_pinned desc, last_activity_at desc);
create index threads_activity on public.threads (last_activity_at desc);
create index threads_created on public.threads (created_at desc);
create index threads_score on public.threads (score desc);
