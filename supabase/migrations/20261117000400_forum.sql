-- ---------------------------------------------------------------------------------------------
-- Visibility helpers
-- ---------------------------------------------------------------------------------------------
create or replace function public.can_view_thread(tid bigint)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.threads t
    where t.id = tid
      and public.can_view_category(t.category_id)
      and (t.removed_at is null or t.author_id = auth.uid() or public.is_moderator())
  );
$$;

create or replace function public.extract_mentions(txt text)
returns text[] language sql immutable set search_path = '' as $$
  select coalesce(array_agg(distinct lower(m[2])), '{}')
  from regexp_matches(coalesce(txt, ''), '(^|[^A-Za-z0-9_@/])@([A-Za-z0-9_]{3,20})', 'g') as m;
$$;

create or replace function public.normalise_tags(t text[])
returns text[] language sql immutable set search_path = '' as $$
  select coalesce(array_agg(distinct x), '{}') from (
    select left(regexp_replace(lower(trim(v)), '[^a-z0-9-]+', '-', 'g'), 24) as x
    from unnest(coalesce(t, '{}')) as v
  ) s where char_length(x) >= 2 and x !~ '^-+$';
$$;

-- ---------------------------------------------------------------------------------------------
-- Thread triggers
-- ---------------------------------------------------------------------------------------------
create or replace function public.before_thread_insert()
returns trigger language plpgsql security definer set search_path = '' as $$
declare
  cat public.forum_categories;
begin
  new.tags := public.normalise_tags(new.tags);
  if auth.role() = 'service_role' then
    return new; -- seeds and server-side staff tooling
  end if;
  new.author_id := auth.uid();
  if not public.can_write(new.author_id) then
    raise exception 'Your account cannot post right now.' using errcode = 'UE403';
  end if;
  select * into cat from public.forum_categories where id = new.category_id;
  if cat.id is null or not public.can_view_category(cat.id) then
    raise exception 'That category is not open to you.' using errcode = 'UE403';
  end if;
  if cat.staff_only and not (public.is_moderator() or exists (select 1 from public.profiles where id = new.author_id and is_staff)) then
    raise exception 'Only staff can start threads here.' using errcode = 'UE403';
  end if;
  perform public.enforce_rate_limit('thread10m:' || new.author_id, 4, 600);
  perform public.enforce_rate_limit('thread1d:' || new.author_id, 20, 86400);
  new.is_official := exists (select 1 from public.profiles where id = new.author_id and is_staff);
  new.last_activity_at := now();
  return new;
end;
$$;
create trigger threads_before_insert before insert on public.threads
  for each row execute function public.before_thread_insert();

create or replace function public.before_thread_update()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  new.tags := public.normalise_tags(new.tags);
  if (new.title is distinct from old.title) or (new.body is distinct from old.body) then
    if auth.role() <> 'service_role' and old.is_locked and not public.is_moderator() then
      raise exception 'This thread is locked.' using errcode = 'UE423';
    end if;
    insert into public.revisions (thread_id, title, body, edited_by) values (old.id, old.title, old.body, auth.uid());
    new.edited_at := now();
  end if;
  return new;
end;
$$;
create trigger threads_before_update before update on public.threads
  for each row execute function public.before_thread_update();

create or replace function public.after_thread_insert()
returns trigger language plpgsql security definer set search_path = '' as $$
declare
  m text;
  target uuid;
begin
  if new.author_id is not null then
    insert into public.thread_subscriptions (user_id, thread_id) values (new.author_id, new.id)
      on conflict do nothing;
    foreach m in array (public.extract_mentions(new.body))[1:10] loop
      select id into target from public.profiles where username = m::extensions.citext;
      if target is not null and public.can_view_thread_for(target, new.id) then
        perform public.notify(target, 'mention', new.author_id, new.id, null, jsonb_build_object('title', new.title));
      end if;
    end loop;
    perform public.recompute_member(new.author_id);
  end if;
  return new;
end;
$$;
create trigger threads_after_insert after insert on public.threads
  for each row execute function public.after_thread_insert();

-- Variant of can_view_thread for an arbitrary member (used when notifying someone else).
create or replace function public.can_view_thread_for(uid uuid, tid bigint)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.threads t join public.forum_categories c on c.id = t.category_id
    where t.id = tid and t.removed_at is null
      and (public.is_moderator(uid) or c.min_tier <= public.member_tier(uid))
  );
$$;

-- ---------------------------------------------------------------------------------------------
-- Reply triggers
-- ---------------------------------------------------------------------------------------------
create or replace function public.before_post_insert()
returns trigger language plpgsql security definer set search_path = '' as $$
declare
  t public.threads;
begin
  if auth.role() = 'service_role' then
    return new;
  end if;
  new.author_id := auth.uid();
  if not public.can_write(new.author_id) then
    raise exception 'Your account cannot post right now.' using errcode = 'UE403';
  end if;
  select * into t from public.threads where id = new.thread_id;
  if t.id is null or t.removed_at is not null or not public.can_view_category(t.category_id) then
    raise exception 'Thread not found.' using errcode = 'UE404';
  end if;
  if t.is_locked and not public.is_moderator() then
    raise exception 'This thread is locked.' using errcode = 'UE423';
  end if;
  perform public.enforce_rate_limit('reply5m:' || new.author_id, 10, 300);
  perform public.enforce_rate_limit('reply1d:' || new.author_id, 200, 86400);
  return new;
end;
$$;
create trigger posts_before_insert before insert on public.posts
  for each row execute function public.before_post_insert();

create or replace function public.before_post_update()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if new.body is distinct from old.body then
    if auth.role() <> 'service_role' and not public.is_moderator()
       and exists (select 1 from public.threads where id = old.thread_id and is_locked) then
      raise exception 'This thread is locked.' using errcode = 'UE423';
    end if;
    insert into public.revisions (post_id, body, edited_by) values (old.id, old.body, auth.uid());
    new.edited_at := now();
  end if;
  return new;
end;
$$;
create trigger posts_before_update before update on public.posts
  for each row execute function public.before_post_update();

create or replace function public.after_post_insert()
returns trigger language plpgsql security definer set search_path = '' as $$
declare
  t public.threads;
  sub record;
  m text;
  target uuid;
  mentioned uuid[] := '{}';
begin
  update public.threads
     set reply_count = reply_count + 1, last_activity_at = new.created_at, last_reply_by = new.author_id
   where id = new.thread_id
   returning * into t;

  if new.author_id is null then
    return new;
  end if;

  insert into public.thread_subscriptions (user_id, thread_id) values (new.author_id, new.thread_id)
    on conflict do nothing;

  foreach m in array (public.extract_mentions(new.body))[1:10] loop
    select id into target from public.profiles where username = m::extensions.citext;
    if target is not null and public.can_view_thread_for(target, t.id) then
      perform public.notify(target, 'mention', new.author_id, t.id, new.id, jsonb_build_object('title', t.title));
      mentioned := mentioned || target;
    end if;
  end loop;

  for sub in
    select user_id from public.thread_subscriptions
    where thread_id = new.thread_id and user_id <> new.author_id and not (user_id = any (mentioned))
  loop
    if public.can_view_thread_for(sub.user_id, t.id) then
      perform public.notify(sub.user_id, 'reply', new.author_id, t.id, new.id, jsonb_build_object('title', t.title));
    end if;
  end loop;

  perform public.recompute_member(new.author_id);
  return new;
end;
$$;
create trigger posts_after_insert after insert on public.posts
  for each row execute function public.after_post_insert();

create or replace function public.after_post_delete()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  update public.threads set reply_count = greatest(reply_count - 1, 0) where id = old.thread_id;
  return old;
end;
$$;
create trigger posts_after_delete after delete on public.posts
  for each row execute function public.after_post_delete();

-- ---------------------------------------------------------------------------------------------
-- Votes feed scores and reputation (+2 per upvote received)
-- ---------------------------------------------------------------------------------------------
create or replace function public.before_vote()
returns trigger language plpgsql security definer set search_path = '' as $$
declare
  owner uuid;
begin
  new.user_id := auth.uid();
  if tg_table_name = 'thread_votes' then
    select author_id into owner from public.threads where id = new.thread_id and public.can_view_thread(new.thread_id);
  else
    select p.author_id into owner from public.posts p
     where p.id = new.post_id and p.removed_at is null and public.can_view_thread(p.thread_id);
  end if;
  if not found then
    raise exception 'Not found.' using errcode = 'UE404';
  end if;
  if owner = new.user_id then
    raise exception 'You cannot vote for your own writing.' using errcode = 'UE403';
  end if;
  if public.has_active_sanction(new.user_id, 'ban') then
    raise exception 'Your account is suspended.' using errcode = 'UE403';
  end if;
  perform public.enforce_rate_limit('vote:' || new.user_id, 300, 3600);
  return new;
end;
$$;
create trigger thread_votes_before before insert on public.thread_votes for each row execute function public.before_vote();
create trigger post_votes_before before insert on public.post_votes for each row execute function public.before_vote();

create or replace function public.after_vote()
returns trigger language plpgsql security definer set search_path = '' as $$
declare
  delta integer := case when tg_op = 'INSERT' then 1 else -1 end;
  r record := case when tg_op = 'INSERT' then new else old end;
  owner uuid;
begin
  if tg_table_name = 'thread_votes' then
    update public.threads set score = score + delta where id = r.thread_id returning author_id into owner;
  else
    update public.posts set score = score + delta where id = r.post_id returning author_id into owner;
  end if;
  if owner is not null then
    update public.profiles set reputation = greatest(reputation + 2 * delta, 0) where id = owner;
    perform public.recompute_member(owner);
  end if;
  return null;
end;
$$;
create trigger thread_votes_after after insert or delete on public.thread_votes for each row execute function public.after_vote();
create trigger post_votes_after after insert or delete on public.post_votes for each row execute function public.after_vote();

-- ---------------------------------------------------------------------------------------------
-- Accepted answers (advice categories): thread author or a moderator marks one reply.
-- ---------------------------------------------------------------------------------------------
create or replace function public.mark_solution(p_thread bigint, p_post bigint)
returns void language plpgsql security definer set search_path = '' as $$
declare
  t public.threads;
  p public.posts;
  advice boolean;
begin
  select * into t from public.threads where id = p_thread;
  if t.id is null then raise exception 'Thread not found.' using errcode = 'UE404'; end if;
  if not (t.author_id = auth.uid() or public.is_moderator()) then
    raise exception 'Only the author can mark a solution.' using errcode = 'UE403';
  end if;
  select is_advice into advice from public.forum_categories where id = t.category_id;
  if not advice then raise exception 'Solutions apply to advice threads only.' using errcode = 'UE400'; end if;

  -- Undo the previous solution's reputation.
  if t.solved_post_id is not null then
    update public.profiles set reputation = greatest(reputation - 15, 0)
     where id = (select author_id from public.posts where id = t.solved_post_id);
  end if;

  if p_post is null then
    update public.threads set solved_post_id = null where id = p_thread;
    return;
  end if;

  select * into p from public.posts where id = p_post and thread_id = p_thread and removed_at is null;
  if p.id is null then raise exception 'Reply not found.' using errcode = 'UE404'; end if;
  update public.threads set solved_post_id = p.id where id = p_thread;
  if p.author_id is not null then
    update public.profiles set reputation = reputation + 15 where id = p.author_id;
    if p.author_id <> auth.uid() then
      perform public.notify(p.author_id, 'solution', auth.uid(), p_thread, p.id, jsonb_build_object('title', t.title));
    end if;
    perform public.recompute_member(p.author_id);
  end if;
end;
$$;

-- ---------------------------------------------------------------------------------------------
-- Polls
-- ---------------------------------------------------------------------------------------------
create or replace function public.before_poll_vote()
returns trigger language plpgsql security definer set search_path = '' as $$
declare
  pl public.polls;
begin
  new.user_id := auth.uid();
  select * into pl from public.polls where id = new.poll_id;
  if pl.id is null or not public.can_view_thread(pl.thread_id) then
    raise exception 'Poll not found.' using errcode = 'UE404';
  end if;
  if pl.closes_at is not null and pl.closes_at < now() then
    raise exception 'This poll has closed.' using errcode = 'UE423';
  end if;
  if new.option_index < 0 or new.option_index >= array_length(pl.options, 1) then
    raise exception 'Unknown option.' using errcode = 'UE400';
  end if;
  if not pl.allow_multiple and exists (select 1 from public.poll_votes where poll_id = pl.id and user_id = new.user_id) then
    raise exception 'You have already voted.' using errcode = 'UE409';
  end if;
  if not public.can_write(new.user_id) and public.has_active_sanction(new.user_id, 'ban') then
    raise exception 'Your account is suspended.' using errcode = 'UE403';
  end if;
  return new;
end;
$$;
create trigger poll_votes_before before insert on public.poll_votes for each row execute function public.before_poll_vote();

create or replace function public.poll_results(p_poll bigint)
returns table (option_index smallint, votes bigint)
language sql stable security definer set search_path = '' as $$
  select v.option_index, count(*) from public.poll_votes v
  join public.polls p on p.id = v.poll_id
  where v.poll_id = p_poll and public.can_view_thread(p.thread_id)
  group by v.option_index;
$$;

-- ---------------------------------------------------------------------------------------------
-- Search, tags, overview
-- ---------------------------------------------------------------------------------------------
create or replace function public.search_forum(q text, lim integer default 20, off integer default 0)
returns table (thread_id bigint, post_id bigint, title text, snippet text, rank real, created_at timestamptz, category_slug text)
language sql stable security invoker set search_path = '' as $$
  with query as (select websearch_to_tsquery('english', q) as tsq)
  select * from (
    select t.id, null::bigint, t.title,
      ts_headline('english', t.body, query.tsq, 'StartSel=[[, StopSel=]], MaxWords=28, MinWords=12, MaxFragments=1'),
      ts_rank(t.search, query.tsq), t.created_at, c.slug
    from public.threads t join public.forum_categories c on c.id = t.category_id, query
    where t.search @@ query.tsq and t.removed_at is null
    union all
    select p.thread_id, p.id, t.title,
      ts_headline('english', p.body, query.tsq, 'StartSel=[[, StopSel=]], MaxWords=28, MinWords=12, MaxFragments=1'),
      ts_rank(p.search, query.tsq) * 0.8, p.created_at, c.slug
    from public.posts p
      join public.threads t on t.id = p.thread_id
      join public.forum_categories c on c.id = t.category_id, query
    where p.search @@ query.tsq and p.removed_at is null and t.removed_at is null
  ) s
  order by 5 desc, 6 desc
  limit least(greatest(lim, 1), 50) offset greatest(off, 0);
$$;

create or replace function public.popular_tags(lim integer default 30)
returns table (tag text, threads bigint)
language sql stable security invoker set search_path = '' as $$
  select tg, count(*) from public.threads, unnest(tags) as tg
  where removed_at is null
  group by tg order by 2 desc, 1 limit least(greatest(lim, 1), 100);
$$;

create or replace function public.category_overview()
returns table (category_id smallint, threads bigint, replies bigint, last_activity_at timestamptz)
language sql stable security invoker set search_path = '' as $$
  select c.id, count(t.id), coalesce(sum(t.reply_count), 0)::bigint, max(t.last_activity_at)
  from public.forum_categories c
  left join public.threads t on t.category_id = c.id and t.removed_at is null
  group by c.id;
$$;

