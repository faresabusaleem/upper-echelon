// Generates "The Planes", the reduced geometric mark derived from the original logo's
// construction: three mutually perpendicular planes (coronal, sagittal, transverse) through a head.
// Usage: node scripts/build-mark.mjs
// Outputs: brand/mark-planes*.svg and src/components/brand/mark-paths.ts (used by <Mark/>).
import { writeFileSync, mkdirSync } from "node:fs";

const YAW = (-20 * Math.PI) / 180;
const PITCH = (22 * Math.PI) / 180;
const D = { cw: 1.25, ch: 0.95, sd: 1.0, sh: 0.95, tw: 1.25, td: 1.0, r: 0.42 };

const project = ([x, y, z]) => {
  const x1 = x * Math.cos(YAW) + z * Math.sin(YAW);
  const z1 = -x * Math.sin(YAW) + z * Math.cos(YAW);
  const y2 = y * Math.cos(PITCH) - z1 * Math.sin(PITCH);
  const z2 = y * Math.sin(PITCH) + z1 * Math.cos(PITCH);
  return [x1, -y2, z2];
};

const quads = [];
for (const a of [-1, 1])
  for (const b of [-1, 1]) {
    quads.push({ plane: "coronal", pts: [[0, 0, 0], [a * D.cw, 0, 0], [a * D.cw, b * D.ch, 0], [0, b * D.ch, 0]] });
    quads.push({ plane: "sagittal", pts: [[0, 0, 0], [0, 0, a * D.sd], [0, b * D.sh, a * D.sd], [0, b * D.sh, 0]] });
    quads.push({ plane: "transverse", pts: [[0, 0, 0], [a * D.tw, 0, 0], [a * D.tw, 0, b * D.td], [0, 0, b * D.td]] });
  }
const P = quads.map((q) => {
  const p = q.pts.map(project);
  return { ...q, p, depth: p.reduce((s, v) => s + v[2], 0) / 4 };
});
const all = P.flatMap((q) => q.p);
const minX = Math.min(...all.map((v) => v[0])), maxX = Math.max(...all.map((v) => v[0]));
const minY = Math.min(...all.map((v) => v[1])), maxY = Math.max(...all.map((v) => v[1]));
const pad = 0.07, w = maxX - minX + 2 * pad, h = maxY - minY + 2 * pad;
const sc = 100 / Math.max(w, h);
const ox = (100 - w * sc) / 2 - (minX - pad) * sc, oy = (100 - h * sc) / 2 - (minY - pad) * sc;
const T = (v) => `${(v[0] * sc + ox).toFixed(2)} ${(v[1] * sc + oy).toFixed(2)}`;
const edge = (q) => `M${T(q.p[1])}L${T(q.p[2])}L${T(q.p[3])}`;
const centre = project([0, 0, 0]);
const axes = [[[-D.cw, 0, 0], [D.cw, 0, 0]], [[0, -D.ch, 0], [0, D.ch, 0]], [[0, 0, -D.sd], [0, 0, D.sd]]];
const axisHalf = (front) =>
  axes
    .map(([a, b]) => {
      const pa = project(a), pb = project(b);
      const pick = front ? (pa[2] < pb[2] ? pa : pb) : pa[2] >= pb[2] ? pa : pb;
      return `M${T(centre)}L${T(pick)}`;
    })
    .join("");

const byPlane = (front) =>
  Object.fromEntries(
    ["coronal", "sagittal", "transverse"].map((pl) => [
      pl,
      P.filter((q) => q.plane === pl && (front ? q.depth <= 0 : q.depth > 0)).map(edge).join(""),
    ]),
  );
const geometry = {
  back: byPlane(false),
  front: byPlane(true),
  axesBack: axisHalf(false),
  axesFront: axisHalf(true),
  head: { cx: +ox.toFixed(2), cy: +oy.toFixed(2), r: +(D.r * sc).toFixed(2) },
};

function svg({ stroke = 2.4, color = "currentColor", ground = "#0b0b0a", bg = false, backAxes = true } = {}) {
  const g = geometry;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" fill="none">
${bg ? `<rect width="100" height="100" fill="${ground}"/>\n` : ""}<g stroke="${color}" stroke-width="${stroke}" stroke-linecap="square">
<path d="${Object.values(g.back).join("")}"/>
${backAxes ? `<path d="${g.axesBack}" opacity="0.45"/>` : ""}
</g>
<circle cx="${g.head.cx}" cy="${g.head.cy}" r="${g.head.r}" fill="${ground}" stroke="${color}" stroke-width="${stroke}"/>
<g stroke="${color}" stroke-width="${stroke}" stroke-linecap="square">
<path d="${Object.values(g.front).join("")}${g.axesFront}"/>
</g>
</svg>
`;
}

mkdirSync("brand", { recursive: true });
writeFileSync("brand/mark-planes.svg", svg());
writeFileSync("brand/mark-planes-gold.svg", svg({ color: "#c2a15f" }));
writeFileSync("brand/mark-planes-icon.svg", svg({ color: "#c2a15f", stroke: 5.5, bg: true, backAxes: false }));
writeFileSync("brand/mark-planes-ivory.svg", svg({ color: "#edeae3", stroke: 2.4 }));
writeFileSync("brand/mark-geometry.json", JSON.stringify(geometry, null, 2));
mkdirSync("src/components/brand", { recursive: true });
writeFileSync(
  "src/components/brand/mark-paths.ts",
  `// Generated by scripts/build-mark.mjs. Do not edit by hand.\nexport const MARK = ${JSON.stringify(geometry, null, 2)} as const;\n`,
);
console.log("mark written");
